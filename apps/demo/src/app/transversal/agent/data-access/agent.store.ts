import { computed, inject, Injectable } from '@angular/core';
import { AgentService } from '@reins-ai/angular';

/** What the app needs to know about the connected AI: whether it is connected and the codes to show. */
@Injectable({ providedIn: 'root' })
export class AgentStore {
  private readonly agent = inject(AgentService);

  readonly connection = computed(() => this.agent.state());
  /** The pairing code, while the bridge asks for it. */
  readonly pairingCode = computed(() => {
    const state = this.agent.state();
    return state.status === 'pairing' ? state.code : null;
  });
  /**
   * The submission waiting for its confirmation code (generated by the library; it never travels over the
   * channel).
   */
  readonly pendingConfirmation = computed(() => {
    const state = this.agent.confirmation();
    return state.status === 'pending' ? state : null;
  });
}
